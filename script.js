// Lightweight, mood-matched effects around the edges of the existing gift popup.
// The current popup design, message and visual stay unchanged.
function renderGiftOpenEffect(n,g){
  const fx=$("#giftFx");
  if(!fx) return;
  fx.innerHTML="";
  const msg=(g[1]||"").toLowerCase();
  let mood="warm";
  if(/😂|🤣|funny|laugh|joke|overthink|chaos|olympic|research|half-day|chhutti|bakwas/.test(msg)) mood="funny";
  else if(/health|paani|water|rest|care|khayal|gentle|soft|body|food|khana|sleep|aaraam/.test(msg)) mood="care";
  else if(/motivat|progress|difficult|strong|step|confidence|journey|patience|hope|future|believe|keep going/.test(msg)) mood="motivation";
  else if(/smile|kind|nature|genuine|warm|special|quality|achhi|pyari|lovely|sweet/.test(msg)) mood="warm";

  const pools={
    funny:["confetti","sparkles","burst","ripple"],
    care:["petals","moonlight","soft","glow","flowers"],
    motivation:["shooting","stars","golden","shimmer","ripple"],
    warm:["sunflower","sparkles","flowers","glow","orbit"]
  };
  const pool=pools[mood];
  let kind=pool[(chapterIndex*15+n)%pool.length];
  if(g[3]==="flower") kind="sunflower";
  if(g[3]==="confetti") kind="confetti";

  const chars={
    flowers:["🌸","❀","✿"], petals:["🌸","❀","·"],
    sparkles:["✦","✧","⋆"], stars:["★","✦","✧"],
    confetti:["✦","•","◆"], sunflower:["🌻","✦"],
    golden:["✦","✧","★"], soft:["♡","✦","·"]
  }[kind] || ["✦","✧","·"];
  const counts={flowers:5,petals:5,sparkles:7,stars:6,confetti:7,sunflower:3,golden:6,soft:5,glow:3,orbit:4,moonlight:4,shimmer:4,shooting:2,burst:7,ripple:4};
  const count=counts[kind]||5;

  for(let i=0;i<count;i++){
    const e=document.createElement("span");
    e.className="gift-fx-particle fx-"+kind;
    e.textContent=chars[i%chars.length];
    // Keep particles in the card's empty outer ring; never place them over the message.
    const side=i%4;
    let left,top;
    if(side===0){left=2+Math.random()*17;top=10+Math.random()*72;}
    else if(side===1){left=81+Math.random()*17;top=10+Math.random()*72;}
    else if(side===2){left=14+Math.random()*72;top=3+Math.random()*13;}
    else {left=14+Math.random()*72;top=84+Math.random()*10;}
    e.style.left=left+"%"; e.style.top=top+"%";
    e.style.setProperty("--delay",(Math.random()*.18)+"s");
    e.style.setProperty("--drift",((Math.random()*2-1)*16)+"px");
    e.style.setProperty("--spin",((Math.random()*2-1)*30)+"deg");
    e.style.setProperty("--scale",(.72+Math.random()*.45).toFixed(2));
    fx.appendChild(e);
  }

  if(["glow","orbit","moonlight","shimmer","shooting","burst","ripple"].includes(kind)){
    const special=document.createElement("span");
    special.className="gift-fx-special fx-"+kind;
    fx.appendChild(special);
  }
}

